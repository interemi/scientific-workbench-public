def populate_inventory_section(project_dir: Path, inventory_payload: dict) -> tuple[str, list[str]]:
    artifacts = []
    if not inventory_payload:
        return "Pendiente de poblar con \\texttt{echelle\\_multispec\\_inventory.py}.", artifacts
    results = inventory_payload.get("results", {})
    files = results.get("files", [])
    lines = [
        f"Se inventariaron {tex_escape(str(results.get('file_count', len(files))))} fichero(s) y {tex_escape(str(results.get('order_count', 'pendiente')))} orden(es).",
        "",
    ]
    if files:
        preview_rows = []
        for item in files[:6]:
            preview_rows.append([
                item.get("file_name", ""),
                str(item.get("order_count", "")),
                str(item.get("lambda_min_global", "")),
                str(item.get("lambda_max_global", "")),
            ])
        write_simple_table(project_dir / "tables" / "inventario_multispec.tex", ["Fichero", "Ordenes", "lambda min", "lambda max"], preview_rows)
        lines.append(r"\input{tables/inventario_multispec}")
        artifacts.append(str(project_dir / "tables" / "inventario_multispec.tex"))
    else:
        lines.append("No hay una tabla de inventario disponible todavia.")
    return "\n".join(lines), artifacts


