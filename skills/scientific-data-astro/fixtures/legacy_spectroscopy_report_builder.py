def cmd_scaffold(args):
    configure_runtime("legacy_spectroscopy_report_builder_scaffold")
    project_dir = Path(args.output_dir).expanduser().resolve()
    validation_issues = validate_scaffold_request(project_dir, args)
    if validation_issues:
        raise InputValidationError(validation_issues)
    (project_dir / "sections").mkdir(parents=True, exist_ok=True)
    (project_dir / "figures").mkdir(parents=True, exist_ok=True)
    (project_dir / "tables").mkdir(parents=True, exist_ok=True)
    scaffold_main_tex(project_dir, args.title, args.author)
    scaffold_sections(project_dir)

    artifacts = {
        "project_dir": str(project_dir),
        "main_tex": str(project_dir / "main.tex"),
        "sections_dir": str(project_dir / "sections"),
        "figures_dir": str(project_dir / "figures"),
        "tables_dir": str(project_dir / "tables"),
        "summary_json": str(Path(args.summary_json).expanduser().resolve(strict=False)) if args.summary_json else None,
        "manifest_json": str(Path(args.manifest_json).expanduser().resolve(strict=False)) if args.manifest_json else None,
    }
    payload = scaffold_payload(
        project_dir,
        status="ok",
        notes=["Proyecto LaTeX estrecho creado en espanol para la practica legacy de espectroscopia."],
        artifacts=artifacts,
        results={
            "output_dir": str(project_dir),
            "section_count": len(SECTION_FILES),
            "created_files": [str(path) for path in scaffold_owned_files(project_dir)],
        },
    )
    emit_scaffold_payload(payload, args)
    if args.manifest_json:
        write_manifest(
            args.manifest_json,
            inputs=[],
            outputs=[project_dir],
            parameters={"tool": SCAFFOLD_TOOL},
            command=" ".join(sys.argv),
            notes=payload["notes"],
        )
    return 0


def emit_blocked_scaffold(args, error: InputValidationError) -> int:
    project_dir = Path(args.output_dir).expanduser().resolve(strict=False)
    artifacts = {
        "project_dir": str(project_dir),
        "summary_json": str(Path(args.summary_json).expanduser().resolve(strict=False)) if args.summary_json else None,
        "manifest_json": str(Path(args.manifest_json).expanduser().resolve(strict=False)) if args.manifest_json else None,
    }
    payload = scaffold_payload(
        project_dir,
        status="blocked",
        notes=["Scaffold bloqueado para evitar sobrescribir archivos o emitir un resultado enganoso."],
        artifacts=artifacts,
        results={
            "output_dir": str(project_dir),
            "section_count": len(SECTION_FILES),
            "created_files": [],
            "blockers": error.issues,
        },
        findings=error.issues,
    )
    skip_summary = any(item.get("argument") == "--summary-json" for item in error.issues)
    emit_scaffold_payload(payload, args, skip_summary_json=skip_summary)
    return 2


def load_json(path: str | None) -> dict:
    if not path:
        return {}
    candidate = Path(path).expanduser().resolve()
    if not candidate.exists():
        return {}
    return json.loads(candidate.read_text(encoding="utf-8"))


def read_csv_rows(path: str | None) -> list[dict]:
    if not path:
        return []
    candidate = Path(path).expanduser()
    if not candidate.exists():
        return []
    with candidate.open(encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def copy_artifact_if_exists(raw_path: str | None, target_dir: Path) -> str | None:
    if not raw_path:
        return None
    source = Path(raw_path).expanduser()
    if not source.exists() or not source.is_file():
        return None
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / source.name
    shutil.copy2(source, target)
    return target.name


def write_simple_table(path: Path, headers: list[str], rows: list[list[str]]) -> None:
    lines = [
        r"\begin{table}[h]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{" + "l" * len(headers) + "}",
        r"\toprule",
        " & ".join(tex_escape(item) for item in headers) + r" \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(tex_escape(item) for item in row) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    write_text(path, "\n".join(lines))


