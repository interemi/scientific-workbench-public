def populate_equivalent_width_section(project_dir: Path, payloads: list[dict]) -> tuple[str, list[str]]:
    artifacts = []
    if not payloads:
        return (
            "Pendiente de poblar con medidas reproducibles de anchura equivalente. "
            "Para Li I 6707.8 en esta ruta puede usarse \\texttt{li6708\\_equivalent\\_width\\_workbench.py}.",
            artifacts,
        )

    lines = ["Medidas de anchura equivalente incorporadas desde helpers reproducibles:", r"\begin{itemize}"]
    figure_blocks = []
    for payload in payloads:
        if not payload:
            continue
        results = payload.get("results") or payload
        label = results.get("line_label") or results.get("target") or payload.get("tool", "EW")
        order = results.get("order_1based", "pendiente")
        ew_ma = results.get("ew_milliangstrom")
        uncertainty_ma = results.get("uncertainty_milliangstrom")
        if ew_ma is not None and uncertainty_ma is not None:
            lines.append(
                rf"\item {tex_escape(str(label))}, orden {tex_escape(str(order))}: EW = {float(ew_ma):.1f} $\pm$ {float(uncertainty_ma):.1f} m\AA."
            )
        elif ew_ma is not None:
            lines.append(rf"\item {tex_escape(str(label))}, orden {tex_escape(str(order))}: EW = {float(ew_ma):.1f} m\AA.")
        else:
            lines.append(rf"\item {tex_escape(str(label))}: medición pendiente de revisar.")
        notes = payload.get("notes") or []
        if notes:
            lines.append(rf"\item Nota metodológica: {tex_escape(str(notes[0]))}")
        figure_name = copy_artifact_if_exists(payload.get("artifacts", {}).get("plot"), project_dir / "figures")
        if figure_name:
            artifacts.append(str(project_dir / "figures" / figure_name))
            figure_blocks.extend(
                [
                    r"\begin{figure}[h]",
                    r"\centering",
                    rf"\includegraphics[width=0.9\linewidth]{{figures/{tex_escape(figure_name)}}}",
                    rf"\caption{{Medida reproducible de {tex_escape(str(label))}.}}",
                    r"\end{figure}",
                ]
            )
    lines.append(r"\end{itemize}")
    lines.extend(figure_blocks)
    return "\n".join(lines), artifacts


def populate_external_reference_discussion(payload: dict) -> str:
    def fmt_number(value, digits: int = 2) -> str:
        try:
            return f"{float(value):.{digits}f}"
        except (TypeError, ValueError):
            return str(value)

    def fmt_yes_no(value) -> str:
        if value is True:
            return "si"
        if value is False:
            return "no"
        return str(value)

    if not payload:
        return (
            "Los resultados automáticos que entran aquí deben leerse con prudencia: la ruta reproduce bien el trabajo no destructivo, "
            "la trazabilidad y una primera pasada científica, pero no sustituye el criterio manual en la inspección de picos CCF, "
            "en la selección final de órdenes ni en la interpretación física de los espectros substraídos."
        )
    results = payload.get("results", {})
    lines = [
        "La comparación externa se usa como control de plausibilidad, no como sustituto del procedimiento del guion.",
        "",
    ]
    pw = results.get("pw_and", {})
    if pw:
        lines.append("Para PW And:")
        lines.append(r"\begin{itemize}")
        for item in pw.get("comparisons", []):
            units = tex_escape(str(item.get("units", "")))
            units_text = f" {units}" if units else ""
            lines.append(
                rf"\item {tex_escape(item.get('metric', 'comparacion'))}: observado={tex_escape(fmt_number(item.get('observed')))}, referencia={tex_escape(fmt_number(item.get('reference')))}{units_text}, estado=\texttt{{{tex_escape(str(item.get('status')))}}}."
            )
        lines.append(r"\end{itemize}")
    gz = results.get("gz_leo", {})
    if gz:
        lines.append("Para 2REJ1101+223/GZ Leo:")
        lines.append(r"\begin{itemize}")
        expected = gz.get("expected_from_orbit", {})
        if expected:
            lines.append(
                rf"\item Fase orbital estimada={fmt_number(expected.get('phase'), 4)}; RV esperada primaria/secundaria={fmt_number(expected.get('primary_expected_rv_kms'))}/{fmt_number(expected.get('secondary_expected_rv_kms'))} km/s."
            )
        lines.append(rf"\item Sospecha de intercambio de componente o centro CCF inadecuado: \texttt{{{tex_escape(fmt_yes_no(gz.get('component_swap_suspected')))}}}.")
        suggestion = gz.get("ccf_window_suggestion", {})
        if suggestion:
            lines.append(
                rf"\item Para revisar \texttt{{fxcor}}: primera pasada amplia \texttt{{window={suggestion.get('broad_first_pass_window')}}}; después probar centros aproximados \texttt{{wincenter={fmt_number(suggestion.get('expected_primary_wincenter_kms'), 1)}}} y \texttt{{wincenter={fmt_number(suggestion.get('expected_secondary_wincenter_kms'), 1)}}} km/s."
            )
        lines.append(r"\end{itemize}")
    warnings = results.get("warnings", [])
    if warnings:
        lines.append("Avisos automáticos:")
        lines.append(r"\begin{itemize}")
        for item in warnings:
            lines.append(rf"\item \texttt{{{tex_escape(str(item))}}}")
        lines.append(r"\end{itemize}")
    return "\n".join(lines)


def cmd_populate(args):
    configure_runtime("legacy_spectroscopy_report_builder_populate")
    project_dir = Path(args.project_dir).expanduser().resolve()
    if not (project_dir / "main.tex").exists():
        raise SystemExit("El directorio indicado no parece un scaffold de legacy_spectroscopy_report_builder.")

    env_payload = load_json(args.envcheck)
    inventory_payload = load_json(args.inventory_summary)
    fxcor_payloads = [load_json(item) for item in args.fxcor_summary]
    rv_payload = load_json(args.rv_summary)
    istarmod_payload = load_json(args.istarmod_summary)
    li_payloads = [load_json(item) for item in args.li_summary]
    external_reference_payload = load_json(args.external_reference_summary)

    generated_artifacts = []
    write_text(project_dir / "sections" / "02_entorno_trazabilidad.tex", populate_env_section(project_dir, env_payload))
    inventory_text, inventory_artifacts = populate_inventory_section(project_dir, inventory_payload)
    generated_artifacts.extend(inventory_artifacts)
    write_text(project_dir / "sections" / "03_inventario_multispec.tex", inventory_text)
    rv_text, vsini_text, rv_artifacts = populate_rv_sections(project_dir, fxcor_payloads, rv_payload)
    generated_artifacts.extend(rv_artifacts)
    write_text(project_dir / "sections" / "04_velocidad_radial.tex", rv_text)
    write_text(project_dir / "sections" / "05_vsini.tex", vsini_text)
    istarmod_text, ist_artifacts = populate_istarmod_section(project_dir, istarmod_payload)
    generated_artifacts.extend(ist_artifacts)
    write_text(project_dir / "sections" / "06_istarmod.tex", istarmod_text)
    ew_text, ew_artifacts = populate_equivalent_width_section(project_dir, li_payloads)
    generated_artifacts.extend(ew_artifacts)
    write_text(project_dir / "sections" / "07_anchuras_equivalentes.tex", ew_text)

    if env_payload:
        practice_assets = env_payload.get("results", {}).get("detected_practice_assets", {})
        objective_text = (
            "La memoria se centra en una práctica universitaria de espectroscopia legacy que combina PDFs de guion, espectros echelle MULTISPE, correlación cruzada con IRAF/fxcor, una calibración FWHM--$v \\sin i$ e iSTARMOD para sustracción espectral.\n\n"
            f"Material detectado automáticamente: {tex_escape(str(practice_assets.get('fits_count', 0)))} FITS, "
            f"calibración externa \\texttt{{{tex_escape(str(practice_assets.get('calibration_csv', 'pendiente')))}}} e "
            f"iSTARMOD local \\texttt{{{tex_escape(str(practice_assets.get('istarmod_root', 'pendiente')))}}}."
        )
        write_text(project_dir / "sections" / "01_objetivo_materiales.tex", objective_text)

    if rv_payload or istarmod_payload or external_reference_payload:
        write_text(project_dir / "sections" / "08_discusion.tex", populate_external_reference_discussion(external_reference_payload))
    write_text(
        project_dir / "sections" / "09_apendices.tex",
        "Incluye aquí los comandos usados, logs relevantes, decisiones manuales sobre la CCF y cualquier comparación con literatura que no quepa en el cuerpo principal.",
    )

    payload = standard_tool_payload(
        "legacy_spectroscopy_report_builder.populate",
        status="ok",
        notes=["Proyecto de memoria actualizado con las salidas reales disponibles."],
        artifacts={"project_dir": str(project_dir), "generated_artifacts": generated_artifacts},
        results={"populated_sections": [item[0] for item in SECTION_FILES]},
    )
    rendered = json.dumps(payload, indent=2, ensure_ascii=True)
    print(rendered)
    if args.summary_json:
        Path(args.summary_json).write_text(rendered + "\n", encoding="utf-8")
    if args.manifest_json:
        inputs = [Path(item).expanduser().resolve() for item in [args.envcheck, args.inventory_summary, args.rv_summary, args.istarmod_summary, args.external_reference_summary] if item]
        inputs.extend(Path(item).expanduser().resolve() for item in args.fxcor_summary)
        inputs.extend(Path(item).expanduser().resolve() for item in args.li_summary)
        write_manifest(args.manifest_json, inputs=inputs, outputs=[project_dir], parameters={"tool": "legacy_spectroscopy_report_builder.populate"}, command=" ".join(sys.argv), notes=payload["notes"])


def main():
    args = parse_args()
    if args.command == "scaffold":
        try:
            return cmd_scaffold(args)
        except InputValidationError as error:
            return emit_blocked_scaffold(args, error)
    elif args.command == "populate":
        cmd_populate(args)
        return 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
